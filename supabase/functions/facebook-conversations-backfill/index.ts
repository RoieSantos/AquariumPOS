// Manual, admin-triggered, one-time-but-safe-to-rerun import of conversation history that already
// exists on the RSPetStop GMA Facebook Page from BEFORE supabase/functions/facebook-messenger-
// webhook existed, or from real customers who aren't added as a Tester while pages_messaging is
// still in Meta App Review (while in Development Mode, that webhook only fires for people with a
// role on the app - see that function's own header comment). This function instead reads the
// Page's conversation history directly via Facebook's Conversations Graph API
// (GET /me/conversations) and backfills it into the SAME ChatbotConversations/ChatbotMessages
// tables the live webhook writes to - so docs/gma-conversations.html shows both without any UI
// changes.
//
// Requires FACEBOOK_PAGE_ACCESS_TOKEN to actually have read access to the Page's conversation
// history - Meta restricts how much of this it hands over even once pages_messaging is approved
// with Advanced Access, so results here are best-effort.
//
// Also requires a FACEBOOK_PAGE_ID secret (set once via `supabase secrets set FACEBOOK_PAGE_ID=...
// --project-ref hymcmesqgpliyyeghpgq`) - deliberately NOT looked up via GET /me, which turns out to
// require the pages_read_engagement permission (confirmed by a live 403 while testing this
// function); avoiding that call means this feature doesn't need to request a permission with no
// other use in this app. Each thread is also capped at
// MESSAGES_PER_CONVERSATION (Facebook's own field-expansion limit per call) and the whole run is
// capped at MAX_CONVERSATION_PAGES so one invocation can't run away - re-run this function again
// later to pick up anything Facebook's pagination didn't reach this time (safe: every message is
// deduped, see below).
//
// Dedup: every imported message is upserted on ChatbotMessages."FacebookMessageId" (the same
// unique index the live webhook already relies on for its own redelivery dedup), so re-running
// this - or overlapping with messages the live webhook has already captured - never creates
// duplicates.
//
// Page-sent messages are recorded with Role 'staff', not 'assistant' - these predate the bot, so
// they were manually typed by a person in Meta Business Suite's native inbox, not generated by
// Claude. SentByUsername is left null since Facebook's API doesn't expose which individual staff
// member sent a given message.
//
// Vision-based payment-screenshot detection (facebook-messenger-webhook's extractPaymentDetails)
// is deliberately skipped here - this is a bulk historical import, and running that over every old
// photo would be a large, mostly-unnecessary Claude API cost spike for messages nobody is waiting
// on a reply to. Photos are still downloaded and stored privately so they display inline either way.
//
// Admin-gated: the caller passes admin_username/admin_password, re-verified via
// is_admin_authorized() on every call (see supabase_chatbot_conversations_backfill.sql, which
// grants anon execute on that existing function) - same trust model as every other admin_*-gated
// feature in this codebase, no stored session.
//
// Name resolution: every run (and the lighter { mode: 'names_only' } run behind the page's "Fetch
// Names" button) also fills ChatbotConversations.FacebookName (what the inbox shows) and a blank
// CustomerName for any row still missing one - the
// live webhook only looks a name up when that customer sends a NEW message, so conversations from
// before pages_messaging was approved stayed as raw PSIDs forever. Tries the User Profile API
// first (needs the separate Business Asset User Profile Access feature), then the Conversations
// API participant name; the first Graph API error is returned
// to the page so a missing permission/feature shows up there instead of only in the logs.
//
// Deploy: supabase functions deploy facebook-conversations-backfill --project-ref hymcmesqgpliyyeghpgq

import { createClient } from 'npm:@supabase/supabase-js@2';
import { getPageAccessToken } from '../_shared/page-tokens.ts';

const DEFAULT_GRAPH_VERSION = 'v21.0';
// Name lookups stop this long after the request started, safely under the Edge Function wall-clock
// limit (a full-inbox names_only run hit it - 504); the participant-list scan gets the first part.
const NAME_TIME_BUDGET_MS = 100_000;
const PARTICIPANT_SCAN_BUDGET_MS = 40_000;
const NAME_LOOKUP_CONCURRENCY = 6;
const CONVERSATIONS_PER_PAGE = 25;
const MESSAGES_PER_CONVERSATION = 100;
const MAX_CONVERSATION_PAGES = 40;

const CORS_HEADERS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
  'Access-Control-Allow-Methods': 'POST, OPTIONS'
};

function jsonResponse(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), { status, headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' } });
}

interface GraphMessage {
  id?: string;
  message?: string;
  created_time?: string;
  from?: { id?: string; name?: string };
  attachments?: { data?: Array<{ image_data?: { url?: string }; mime_type?: string }> };
}

interface GraphConversation {
  participants?: { data?: Array<{ id?: string; name?: string }> };
  messages?: { data?: GraphMessage[] };
}

async function downloadAndStoreImage(
  supabase: ReturnType<typeof createClient>,
  psid: string,
  sourceUrl: string
): Promise<{ path: string; signedUrl: string } | null> {
  try {
    const res = await fetch(sourceUrl);
    if (!res.ok) return null;
    const contentType = res.headers.get('content-type') || 'image/jpeg';
    const ext = contentType.includes('png') ? 'png' : contentType.includes('webp') ? 'webp' : contentType.includes('gif') ? 'gif' : 'jpg';
    const bytes = new Uint8Array(await res.arrayBuffer());
    // "backfill-" prefix + a random suffix (rather than just Date.now(), like the live webhook
    // uses) since this loop can process many messages fast enough to collide on the millisecond.
    const path = `${psid}/backfill-${Date.now()}-${Math.random().toString(36).slice(2, 8)}.${ext}`;

    const { error: uploadError } = await supabase.storage.from('chatbot-attachments').upload(path, bytes, { contentType, upsert: false });
    if (uploadError) return null;

    const { data: signedData, error: signError } = await supabase.storage.from('chatbot-attachments').createSignedUrl(path, 60 * 60 * 24 * 60);
    if (signError || !signedData?.signedUrl) return null;

    return { path, signedUrl: signedData.signedUrl };
  } catch {
    return null;
  }
}

// Same lookup as facebook-messenger-webhook's fetchFacebookProfileName, but returns the Graph API
// error text so resolveMissingNames can report WHY names aren't coming back.
async function fetchProfileName(psid: string, pageAccessToken: string, graphVersion: string): Promise<{ name: string | null; error: string | null }> {
  try {
    const res = await fetch(`https://graph.facebook.com/${graphVersion}/${psid}?fields=first_name,last_name,name&access_token=${pageAccessToken}`);
    if (!res.ok) {
      const body = await res.json().catch(() => null);
      return { name: null, error: body?.error?.message || `HTTP ${res.status}` };
    }
    const body = await res.json();
    const name = (body.name || [body.first_name, body.last_name].filter(Boolean).join(' ')).trim();
    return { name: name || null, error: name ? null : 'Profile returned no name' };
  } catch (err) {
    return { name: null, error: err instanceof Error ? err.message : 'network error' };
  }
}

// Participant names from /me/conversations, without the message payload - used by names_only mode
// as the fallback source (the full import collects these while it walks the threads anyway).
async function fetchParticipantNames(pageId: string, pageAccessToken: string, graphVersion: string, stopAt: number): Promise<Map<string, string>> {
  const names = new Map<string, string>();
  let url: string | null = `https://graph.facebook.com/${graphVersion}/me/conversations?fields=participants&limit=100&access_token=${pageAccessToken}`;
  let pages = 0;
  while (url && pages < MAX_CONVERSATION_PAGES && Date.now() < stopAt) {
    pages++;
    const res = await fetch(url);
    if (!res.ok) break;
    const page = await res.json();
    for (const conv of (page.data || []) as GraphConversation[]) {
      const customer = conv.participants?.data?.find((p) => p.id && p.id !== pageId);
      if (customer?.id && customer.name) names.set(customer.id, customer.name);
    }
    url = typeof page.paging?.next === 'string' ? page.paging.next : null;
  }
  return names;
}

// One customer's name from their own thread's participant list - catches anyone the bulk
// fetchParticipantNames scan didn't reach (page cap / pagination).
async function fetchThreadParticipantName(psid: string, pageId: string, pageAccessToken: string, graphVersion: string): Promise<string | null> {
  try {
    const res = await fetch(`https://graph.facebook.com/${graphVersion}/${pageId}/conversations?platform=messenger&user_id=${psid}&fields=participants&access_token=${pageAccessToken}`);
    if (!res.ok) return null;
    const body = await res.json();
    const participants: Array<{ id?: string; name?: string }> = body.data?.[0]?.participants?.data || [];
    return participants.find((p) => p.id === psid)?.name?.trim() || null;
  } catch {
    return null;
  }
}

async function resolveMissingNames(
  supabase: ReturnType<typeof createClient>,
  participantNames: Map<string, string>,
  pageId: string,
  pageAccessToken: string,
  graphVersion: string,
  deadline: number
): Promise<{ namesMissing: number; namesResolved: number; namesRemaining: number; nameError: string | null }> {
  // Rows missing their Facebook name (FacebookName, sql/supabase_gma_conversation_facebook_name.sql -
  // the name the inbox shows, separate from the CRM/order CustomerName) or with no name at all.
  // Falls back to the CustomerName-only check if that SQL isn't run yet.
  let hasFacebookNameColumn = true;
  let { data: rows, error: rowsError } = await supabase
    .from('ChatbotConversations')
    .select('Psid, PageId, CustomerName')
    .or('FacebookName.is.null,FacebookName.eq.,CustomerName.is.null,CustomerName.eq.')
    .order('LastMessageAtUtc', { ascending: false, nullsFirst: false });
  if (rowsError) {
    hasFacebookNameColumn = false;
    ({ data: rows } = await supabase
      .from('ChatbotConversations')
      .select('Psid, PageId, CustomerName')
      .or('CustomerName.is.null,CustomerName.eq.')
      .order('LastMessageAtUtc', { ascending: false, nullsFirst: false }));
  }
  // Messenger PSIDs only - website-widget chats (PageId 'website') have no Facebook name.
  const missing = ((rows || []) as Array<{ Psid: string; PageId: string | null; CustomerName: string | null }>)
    .filter((r) => r.PageId !== 'website' && /^\d+$/.test(r.Psid));
  let namesResolved = 0;
  let namesTried = 0;
  let nameError: string | null = null;

  const resolveOne = async (row: { Psid: string; PageId: string | null; CustomerName: string | null }) => {
    // Each Page's own token (FACEBOOK_PAGE_TOKENS) - another Page's token can't see its customers.
    const rowPageId = row.PageId || pageId;
    const token = getPageAccessToken(rowPageId) || pageAccessToken;
    // Participant list first (already fetched, no extra call), then the Profile API - which also
    // counts toward the Business Asset User Profile Access test calls Meta's App Review wants to see.
    let name = participantNames.get(row.Psid) || null;
    if (!name) {
      const profile = await fetchProfileName(row.Psid, token, graphVersion);
      if (profile.error) console.error(`Profile lookup failed for psid ${row.Psid}: ${profile.error}`);
      name = profile.name || (await fetchThreadParticipantName(row.Psid, rowPageId, token, graphVersion));
      if (!name) {
        nameError = nameError || profile.error;
        return;
      }
    }
    // CustomerName is only filled when blank - a name the customer/staff gave for orders is kept.
    const update: Record<string, unknown> = hasFacebookNameColumn ? { FacebookName: name } : {};
    if (!String(row.CustomerName || '').trim()) {
      update.CustomerName = name;
      update.CustomerNameSource = 'FacebookProfile';
    }
    const { error } = await supabase.from('ChatbotConversations').update(update).eq('Psid', row.Psid);
    if (!error) namesResolved++;
  };

  // A few lookups at a time, and stop before the Edge Function wall-clock limit (it 504'd on a
  // full inbox) - anything left is reported as namesRemaining; just run it again for the rest.
  let next = 0;
  await Promise.all(Array.from({ length: NAME_LOOKUP_CONCURRENCY }, async () => {
    while (next < missing.length && Date.now() < deadline) {
      const row = missing[next++];
      namesTried++;
      await resolveOne(row);
    }
  }));
  return { namesMissing: missing.length, namesResolved, namesRemaining: missing.length - namesTried, nameError };
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: CORS_HEADERS });
  if (req.method !== 'POST') return jsonResponse({ error: 'Use POST.' }, 405);

  const supabaseUrl = Deno.env.get('SUPABASE_URL');
  const serviceRoleKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY');
  const anonKey = Deno.env.get('SUPABASE_ANON_KEY');
  const pageAccessToken = Deno.env.get('FACEBOOK_PAGE_ACCESS_TOKEN');
  const pageId = Deno.env.get('FACEBOOK_PAGE_ID');
  const graphVersion = Deno.env.get('FACEBOOK_GRAPH_API_VERSION') || DEFAULT_GRAPH_VERSION;

  if (!supabaseUrl || !serviceRoleKey || !anonKey || !pageAccessToken || !pageId) {
    return jsonResponse({
      error: !pageId
        ? "Missing the FACEBOOK_PAGE_ID secret. Find your Page's numeric ID (Page Settings > About, or Meta Business Suite > Page Settings > General) and set it with: supabase secrets set FACEBOOK_PAGE_ID=<id> --project-ref hymcmesqgpliyyeghpgq"
        : 'facebook-conversations-backfill is missing one or more required secrets.'
    }, 500);
  }

  let adminUsername: string;
  let adminPassword: string;
  let namesOnly = false;
  try {
    const body = await req.json();
    adminUsername = String(body.admin_username ?? '');
    adminPassword = String(body.admin_password ?? '');
    namesOnly = body.mode === 'names_only';
    if (!adminUsername || !adminPassword) throw new Error('missing field');
  } catch {
    return jsonResponse({ error: 'Body must be JSON: { admin_username, admin_password }.' }, 400);
  }

  const anonClient = createClient(supabaseUrl, anonKey);
  const { data: isAuthorized, error: authError } = await anonClient.rpc('is_admin_authorized', {
    p_username: adminUsername,
    p_password: adminPassword
  });
  if (authError || !isAuthorized) {
    return jsonResponse({ error: 'Not authorized.' }, 403);
  }

  const supabase = createClient(supabaseUrl, serviceRoleKey);

  if (namesOnly) {
    try {
      const startedAt = Date.now();
      const participantNames = await fetchParticipantNames(pageId, pageAccessToken, graphVersion, startedAt + PARTICIPANT_SCAN_BUDGET_MS);
      return jsonResponse({ ok: true, ...(await resolveMissingNames(supabase, participantNames, pageId, pageAccessToken, graphVersion, startedAt + NAME_TIME_BUDGET_MS)) });
    } catch (err) {
      return jsonResponse({ error: err instanceof Error ? err.message : 'Unexpected error.' }, 500);
    }
  }

  try {
    const participantNames = new Map<string, string>();
    let conversationsSeen = 0;
    let conversationsUpserted = 0;
    let messagesProcessed = 0;
    let imagesStored = 0;
    let pagesFetched = 0;
    // Conversations where Facebook confirmed the thread exists (it showed up in /me/conversations,
    // with participants) but handed back zero messages - the strongest available signal that Meta
    // is withholding message CONTENT for that customer (typically because they aren't a Tester/
    // Admin on the app while pages_messaging is still in Development Mode/Standard Access), rather
    // than the conversation genuinely being empty. Surfaced in the response so this doesn't have to
    // be guessed at from staff reports of "the conversation synced but has no messages".
    let conversationsWithNoMessages = 0;

    const fields = 'participants,messages.limit(' + MESSAGES_PER_CONVERSATION + '){message,from,created_time,attachments{data{image_data,mime_type}}}';
    let url: string | null =
      `https://graph.facebook.com/${graphVersion}/me/conversations?fields=${encodeURIComponent(fields)}&limit=${CONVERSATIONS_PER_PAGE}&access_token=${pageAccessToken}`;

    while (url && pagesFetched < MAX_CONVERSATION_PAGES) {
      pagesFetched++;
      const res = await fetch(url);
      if (!res.ok) {
        console.error('Conversations Graph API call failed:', await res.text());
        break;
      }
      const page = await res.json();
      const conversations: GraphConversation[] = page.data || [];

      for (const conv of conversations) {
        conversationsSeen++;
        const participants = conv.participants?.data || [];
        const customer = participants.find((p) => p.id && p.id !== pageId);
        if (!customer?.id) continue; // couldn't tell who the customer is - skip rather than guess

        const psid = customer.id;
        if (customer.name) participantNames.set(psid, customer.name);

        const { error: upsertConvErr } = await supabase
          .from('ChatbotConversations')
          .upsert({ Psid: psid, PageId: pageId, CustomerName: customer.name || null }, { onConflict: 'Psid', ignoreDuplicates: true });
        if (!upsertConvErr) conversationsUpserted++;

        const rawMessages = conv.messages?.data || [];
        if (rawMessages.length === 0) conversationsWithNoMessages++;
        const rows: Record<string, unknown>[] = [];

        for (const msg of rawMessages) {
          if (!msg.id) continue;
          const isFromPage = msg.from?.id === pageId;
          const text = (msg.message || '').trim();

          let attachmentPath: string | null = null;
          let attachmentUrl: string | null = null;
          let attachmentType: string | null = null;
          const imageAttachment = msg.attachments?.data?.find((a) => a.image_data?.url);
          if (imageAttachment?.image_data?.url) {
            const stored = await downloadAndStoreImage(supabase, psid, imageAttachment.image_data.url);
            if (stored) {
              attachmentPath = stored.path;
              attachmentUrl = stored.signedUrl;
              attachmentType = 'image';
              imagesStored++;
            }
          }

          const content = text || (attachmentUrl ? '[Photo]' : '');
          if (!content) continue;

          rows.push({
            Psid: psid,
            Role: isFromPage ? 'staff' : 'user',
            Content: content,
            FacebookMessageId: msg.id,
            CreatedAtUtc: msg.created_time || new Date().toISOString(),
            AttachmentPath: attachmentPath,
            AttachmentUrl: attachmentUrl,
            AttachmentType: attachmentType
          });
        }

        if (rows.length > 0) {
          const { error: insertErr } = await supabase
            .from('ChatbotMessages')
            .upsert(rows, { onConflict: 'FacebookMessageId', ignoreDuplicates: true });
          if (insertErr) {
            console.error('Failed to backfill messages for psid', psid, insertErr.message);
          } else {
            messagesProcessed += rows.length;
          }
        }
      }

      const next = page.paging?.next;
      url = typeof next === 'string' ? next : null;
    }

    // The full import has usually used most of the time already - names get a short window, and
    // names_only runs (or the next import) pick up the rest.
    const names = await resolveMissingNames(supabase, participantNames, pageId, pageAccessToken, graphVersion, Date.now() + 30_000);

    return jsonResponse({
      ok: true,
      ...names,
      conversationsSeen,
      conversationsUpserted,
      messagesProcessed,
      imagesStored,
      pagesFetched,
      conversationsWithNoMessages,
      note:
        conversationsWithNoMessages > 0
          ? `${conversationsWithNoMessages} conversation(s) synced but came back with zero messages - Facebook likely withheld the content because those customers aren't Testers/Admins on the app yet (Development Mode restriction). This should resolve once pages_messaging is approved with Advanced Access.`
          : undefined
    });
  } catch (err) {
    console.error('Unhandled error in facebook-conversations-backfill:', err instanceof Error ? err.message : err);
    return jsonResponse({ error: err instanceof Error ? err.message : 'Unexpected error.' }, 500);
  }
});
