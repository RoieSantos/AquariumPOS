INSERT INTO #plan
SELECT 2,
       CASE WHEN g.Known = 1 OR grp.nKnown = 0 THEN 'KEEP' ELSE 'DEACTIVATE' END,
       g.Code, g.Name,
       STUFF((SELECT ', ' + k.Code FROM #good k WHERE k.VariationId = g.VariationId AND k.Known = 1 FOR XML PATH('')), 1, 2, ''),
       g.QuantityInStock, g.VariationId, NULL,
       CASE WHEN g.Known = 1 THEN 'code exists in Pancake/portal'
            WHEN grp.nKnown = 0 THEN 'none of the items sharing this variation is in Pancake/portal - decide by hand'
            ELSE 'same Pancake variation as a kept item' END
FROM #good g JOIN grp ON grp.VariationId = g.VariationId;

