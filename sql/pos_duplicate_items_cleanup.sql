                    Stock decimal(18,2), OldVariationId nvarchar(100), NewVariationId nvarchar(100), Reason nvarchar(300));

-- ---------- Group 1: VariationId is a Pancake PRODUCT id ----------
;WITH g1 AS (
    SELECT a.* FROM #act a
    WHERE a.VariationId <> ''
      AND NOT EXISTS (SELECT 1 FROM #pk p WHERE p.VariationId = a.VariationId)
      AND EXISTS (SELECT 1 FROM #pk p WHERE p.ProductId = a.VariationId)
), twin AS (
    SELECT g1.Code,
           COUNT(DISTINCT t.VariationId) AS nVar,
           MIN(t.VariationId) AS anyVar,
           COUNT(DISTINCT CASE WHEN UPPER(t.Name) = UPPER(g1.Name) THEN t.VariationId END) AS nSame,
           MIN(CASE WHEN UPPER(t.Name) = UPPER(g1.Name) THEN t.VariationId END) AS sameVar
    FROM g1 LEFT JOIN #good t ON t.ProductId = g1.VariationId
    GROUP BY g1.Code
)
INSERT INTO #plan
SELECT 1,
       CASE WHEN g1.Known = 1 OR tw.nVar = 0 THEN 'KEEP' ELSE 'DEACTIVATE' END,
       g1.Code, g1.Name,
       STUFF((SELECT DISTINCT ', ' + t.Code FROM #good t WHERE t.ProductId = g1.VariationId FOR XML PATH('')), 1, 2, ''),
       g1.QuantityInStock, g1.VariationId,
       CASE WHEN tw.nVar = 1 THEN tw.anyVar WHEN tw.nSame = 1 THEN tw.sameVar END,
       CASE WHEN g1.Known = 1 THEN 'code exists in Pancake/portal'
            WHEN tw.nVar = 0 THEN 'no other POS item holds this Pancake product - would become unsellable'
            WHEN tw.nVar = 1 OR tw.nSame = 1 THEN 'Pancake product id stored as variation id; real item exists'
            ELSE 'Pancake product id stored as variation id; real item exists; several variations - saved lines NOT repointed (fix by hand)' END
FROM g1 JOIN twin tw ON tw.Code = g1.Code;

-- ---------- Group 2: several active items on one Pancake variation ----------
;WITH grp AS (
