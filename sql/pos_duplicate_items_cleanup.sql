-- Repoint saved lines: product id -> real variation id (the product id never worked in Pancake).
DECLARE @t sysname, @sql nvarchar(max);
DECLARE tc CURSOR LOCAL FAST_FORWARD FOR
    SELECT TABLE_NAME FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_NAME IN ('ItemLedgerEntry', 'AdvanceOrderLines', 'OnlineOrderLines') AND COLUMN_NAME = 'VariationId';
OPEN tc; FETCH NEXT FROM tc INTO @t;
WHILE @@FETCH_STATUS = 0
BEGIN
    SET @sql = N'UPDATE l SET VariationId = m.NewVariationId FROM ' + QUOTENAME(@t) + N' l
        JOIN (SELECT DISTINCT OldVariationId, NewVariationId FROM #plan
              WHERE [Group] = 1 AND Action = ''DEACTIVATE'' AND NewVariationId IS NOT NULL) m
          ON m.OldVariationId = l.VariationId;
        PRINT CONCAT(@@ROWCOUNT, '' line(s) repointed in ' + @t + N''');';
    EXEC sp_executesql @sql;
    FETCH NEXT FROM tc INTO @t;
END
CLOSE tc; DEALLOCATE tc;

COMMIT;
