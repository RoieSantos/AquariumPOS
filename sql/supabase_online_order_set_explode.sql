-- SET package explosion on the portal's To Ship - per "is it possible to apply this routine into the
-- Portal too??" (Phase 1). Ports the desktop POS's PrepareSetAssemblyForOrder (OnlineOrdersForm.cs):
-- when an order has a line whose category is SET, staff pick the BOM package for it (once per product,
-- remembered), review the package's components (swap variants, change quantities, drop a component),
-- and the components are added to the Pancake order as extra lines at price 0 - so the order total does
-- not change but Pancake (and everything that reads its lines: stock, serials, ledger) sees the parts.
--
-- What this adds:
--   1. public."OnlineOrderSetPackageMap" - the portal copy of the POS's local dbo.OnlineOrderSetPackageMap
--      (VariationId/ItemCode -> PackageName). Starts empty; fills as staff map lines on the portal.
--   2. staff_get_online_order_set_assembly(order): re-reads the order from Pancake, then returns its SET
--      lines, the package each resolves to (or null = staff must pick), each package's components with
--      variant options + defaults, and the list of packages to pick from.
--   3. staff_get_set_package_components(package, set qty): components for a package picked in the dialog.
--   4. staff_save_online_order_set_materials(order, sets): rebuilds the Pancake order's items - drops the
--      old "SET Material for <set>" lines, writes "SET Materials: ..." on the SET line's note, appends the
--      new component lines (price 0) - PATCHes Pancake (PUT on 404/405, bank_payments restored), then
--      re-reads the order so OnlineOrderLines matches Pancake.
--
-- Same conventions as the POS, so a POS run and a portal run on the same order replace each other's
-- materials instead of doubling them: component note "SET Material for <SET line name>", SET line note
-- line "SET Materials: <name> x <qty>; ...".
--
-- Differences from the POS (on purpose):
--   - The item list is built from Pancake's OWN copy of the order (GET), not from local lines, so per-item
--     discounts / wholesale / bonus flags and one-time products on the other lines are sent back as they
--     were (the POS resets discounts to 0 and turns one-time products into catalog products).
--   - Every component must resolve to a Pancake product (VariationId) or the save is refused - a
--     one-time product would never deduct stock, which is the point of exploding.
--   - Package matching uses the Supabase copy of the packages (CompleteAquariumSetHeader/Line, edited on
--     the Customer Aquarium page). The POS reads its own LOCAL copy - the two are NOT synced.
--
-- Add-ons (section 6): Media (up to 5) / Light / Pump / Pipe / Mesh Bag items NOT in the package can be added
-- in the dialog, like the POS's accessory slots.
--
-- Run AFTER supabase_online_order_sync_no_long_locks.sql and supabase_online_order_refresh_lines_before_ship.sql.
-- Creates the package tables itself if supabase_customer_aquarium_tables.sql was never run (they start
-- empty - copy the POS's packages over with local_export_complete_aquarium_sets.sql). Safe to re-run.

