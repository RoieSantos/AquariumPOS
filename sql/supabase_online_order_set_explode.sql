  );
$$;

-- Package for a SET line: header VariantID = VariationId, then a saved mapping by VariationId, then by
-- ItemCode (OnlineOrdersForm.cs TryResolveSetPackageMapping). Only packages that have BOM lines count.
create or replace function public._resolve_set_package(p_variation_id text, p_item_code text)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select h."PackageName" from public."CompleteAquariumSetHeader" h
      where nullif(trim(p_variation_id), '') is not null
        and lower(trim(coalesce(h."VariantID", ''))) = lower(trim(p_variation_id))
        and public._set_package_has_lines(h."PackageName")
      order by h."PackageName"
      limit 1),
    (select h."PackageName" from public."OnlineOrderSetPackageMap" m
      join public."CompleteAquariumSetHeader" h on lower(trim(h."PackageName")) = lower(trim(m."PackageName"))
      where nullif(trim(p_variation_id), '') is not null
        and m."MatchType" = 'VariationId' and m."MatchValue" = trim(p_variation_id)
        and public._set_package_has_lines(h."PackageName")
      limit 1),
    (select h."PackageName" from public."OnlineOrderSetPackageMap" m
      join public."CompleteAquariumSetHeader" h on lower(trim(h."PackageName")) = lower(trim(m."PackageName"))
      where nullif(trim(p_item_code), '') is not null
        and m."MatchType" = 'ItemCode' and m."MatchValue" = trim(p_item_code)
        and public._set_package_has_lines(h."PackageName")
      limit 1)
  );
$$;

-- A package's components for p_set_qty sets: quantity = BOM qty x set qty (truncated, as the POS does),
-- the variant options of each component's main product and the default pick (exact code, exact name,
-- name contains, or the only variant - MainForm.cs FindDefaultAquariumVariantSelection).
-- requires_choice = has variants but none matched, so staff must pick one. sealant_choice = the variants
-- are Black / Clear sealant: never defaulted, staff pick the colour at Ready to Ship.
create or replace function public._set_package_components(p_package text, p_set_qty int)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_line record;
  v_item_no text;
  v_item_name text;
  v_main_code text;
  v_variants jsonb;
  v_default jsonb;
  v_base_variation text;
  v_sealant boolean;
  v_result jsonb := '[]'::jsonb;
begin
  for v_line in
    select l.* from public."CompleteAquariumSetLine" l
    where lower(trim(l."PackageName")) = lower(trim(p_package))
      and trim(coalesce(l."ItemNo", '')) <> ''
    order by l."EntryNo"
  loop
    v_item_no := trim(v_line."ItemNo");
    v_item_name := coalesce(nullif(trim(v_line."ItemName"), ''), v_item_no);
    v_main_code := null;
    v_base_variation := null;
    v_sealant := false;

    select coalesce(nullif(trim(v."MainItemCode"), ''), v_item_no) into v_main_code
    from public."Variants" v
    where v."MainItemCode" = v_item_no or v."ItemCode" = v_item_no
    order by (v."MainItemCode" = v_item_no) desc, v."VariationId"
    limit 1;
    v_main_code := coalesce(v_main_code, v_item_no);

    select coalesce(jsonb_agg(x order by x ->> 'name', x ->> 'item_code'), '[]'::jsonb) into v_variants
    from (
      select distinct on (v."VariationId") jsonb_build_object(
        'variation_id', v."VariationId",
        'item_code', coalesce(nullif(trim(v."ItemCode"), ''), v."MainItemCode"),
        'name', coalesce(nullif(trim(v."VariantName"), ''), nullif(trim(vi."Name"), ''), nullif(trim(vi."Description"), ''),
                         coalesce(nullif(trim(v."ItemCode"), ''), v."MainItemCode")),
        'description', coalesce(nullif(trim(vi."Description"), ''), nullif(trim(mi."Description"), ''), ''),
        'variant_name', coalesce(nullif(trim(v."VariantName"), ''), ''),
        'sku', coalesce(nullif(trim(v."SKU"), ''), nullif(trim(vi."SKU"), ''), ''),
        'price', coalesce(v."Price", vi."Price", mi."Price", v_line."Price")
      ) as x
      from public."Variants" v
      left join public."Items" vi on vi."Code" = coalesce(nullif(trim(v."ItemCode"), ''), v."MainItemCode")
      left join public."Items" mi on mi."Code" = v."MainItemCode"
      where v."MainItemCode" = v_main_code
      order by v."VariationId"
    ) s;

    v_default := null;
    if jsonb_array_length(v_variants) > 0 then
      -- SKU first: variants of one product share the item code (AST-011-BlackPaint / -WhitePaint), and
      -- the package line's name is usually the exact SKU.
      select x into v_default from jsonb_array_elements(v_variants) x
      where x ->> 'sku' <> '' and lower(x ->> 'sku') in (lower(v_item_name), lower(v_item_no)) limit 1;
      if v_default is null then
        select x into v_default from jsonb_array_elements(v_variants) x
        where lower(x ->> 'item_code') = lower(v_item_no) limit 1;
      end if;
      if v_default is null then
        select x into v_default from jsonb_array_elements(v_variants) x
        where lower(x ->> 'name') = lower(v_item_name) or lower(x ->> 'description') = lower(v_item_name) limit 1;
      end if;
      if v_default is null then
        select x into v_default from jsonb_array_elements(v_variants) x
        where position(lower(v_item_name) in lower(x ->> 'name')) > 0
           or (x ->> 'name' <> '' and position(lower(x ->> 'name') in lower(v_item_name)) > 0)
        limit 1;
      end if;
      if v_default is null and jsonb_array_length(v_variants) = 1 then
        v_default := v_variants -> 0;
      end if;
      -- Black / Clear sealant variants (same rule as the Sealant Sales report): no default - staff
      -- choose the colour at Ready to Ship; the stock check counts either colour.
      -- Also when the package line itself names a sealant (e.g. "AQ-021-BlackSealant") and the product
      -- has more than one variant - the colour on the package line is only an example, staff choose.
      v_sealant := (select count(*) from jsonb_array_elements(v_variants) x
                    where (coalesce(x ->> 'name', '') || ' ' || coalesce(x ->> 'variant_name', '') || ' ' || coalesce(x ->> 'sku', '')) ~* 'sealant'
                      and (coalesce(x ->> 'name', '') || ' ' || coalesce(x ->> 'variant_name', '') || ' ' || coalesce(x ->> 'sku', '')) ~* '(black|clear)') >= 2
                   or (v_item_name ~* 'sealant' and jsonb_array_length(v_variants) >= 2);
      if v_sealant then
        v_default := null;
      end if;
    else
      select nullif(trim(i."VariationId"), '') into v_base_variation
      from public."Items" i where i."Code" = v_item_no limit 1;
      v_default := jsonb_build_object(
        'variation_id', v_base_variation,
        'item_code', v_item_no,
        'name', v_item_name,
        'description', coalesce((select nullif(trim(i."Description"), '') from public."Items" i where i."Code" = v_item_no limit 1), v_item_name),
        'variant_name', '',
        'sku', coalesce((select nullif(trim(i."SKU"), '') from public."Items" i where i."Code" = v_item_no limit 1), ''),
        'price', v_line."Price"
      );
    end if;

    v_result := v_result || jsonb_build_array(jsonb_build_object(
      'bom_item_no', v_item_no,
      'bom_item_name', v_item_name,
      'main_item_code', v_main_code,
      'sealant_choice', v_sealant,
      'qty_per', v_line."Quantity",
      'quantity', trunc(v_line."Quantity" * greatest(p_set_qty, 1)),
      'variants', v_variants,
      'default', v_default,
      'requires_choice', jsonb_array_length(v_variants) > 0 and v_default is null
    ));
  end loop;

  return v_result;
end;
$$;

