-- In Stock serials of one item / variant at a warehouse (same match as the stock check).
create or replace function public._set_serials_in_stock(p_item_code text, p_variation_id text, p_warehouse text)
returns int
language sql
stable
security definer
set search_path = public
as $$
  select count(*)::int from public."ItemSerialTracking" s
  where s."Status" = 'IN_STOCK'
    and s."Location" = p_warehouse
    and s."ItemCode" = p_item_code
    and coalesce(nullif(trim(s."VariantCode"), ''), '') = coalesce(nullif(trim(p_variation_id), ''), '');
$$;

-- Adds stock to _set_package_components' output for the order's branch (per "only show the item with
-- available serials"): each component gets 'serial_tracked' (a production item - AQ-% code or a production
-- category, same rule as the stock check) and, when tracked, each variant / the default gets 'in_stock'.
-- The dialog then lists only the variants with serials in stock. No warehouse -> unchanged.
create or replace function public._set_components_add_stock(p_components jsonb, p_warehouse text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(jsonb_agg(
    case when not t.tracked or p_warehouse is null then c || jsonb_build_object('serial_tracked', t.tracked)
    else c || jsonb_build_object(
      'serial_tracked', true,
      'variants', (select coalesce(jsonb_agg(
                     v || jsonb_build_object('in_stock', public._set_serials_in_stock(v ->> 'item_code', v ->> 'variation_id', p_warehouse))
                     order by vo), '[]'::jsonb)
                   from jsonb_array_elements(coalesce(c -> 'variants', '[]'::jsonb)) with ordinality as ve(v, vo)),
      'default', case when jsonb_typeof(c -> 'default') = 'object'
                      then (c -> 'default') || jsonb_build_object('in_stock',
                             public._set_serials_in_stock(c -> 'default' ->> 'item_code', c -> 'default' ->> 'variation_id', p_warehouse))
                      else c -> 'default' end)
    end
    order by o), '[]'::jsonb)
  from jsonb_array_elements(coalesce(p_components, '[]'::jsonb)) with ordinality as e(c, o)
  cross join lateral (
    select upper(coalesce(c -> 'default' ->> 'item_code', c -> 'variants' -> 0 ->> 'item_code', c ->> 'bom_item_no', '')) like 'AQ-%'
        or coalesce((select cat."IsProductionCategory" from public."Categories" cat
                     where cat."Code" = nullif(public._online_order_line_category(
                       coalesce(c -> 'default' ->> 'variation_id', c -> 'variants' -> 0 ->> 'variation_id'),
                       coalesce(c -> 'default' ->> 'item_code', c -> 'variants' -> 0 ->> 'item_code', c ->> 'bom_item_no')), '')
                     limit 1), false) as tracked
  ) t;
$$;

