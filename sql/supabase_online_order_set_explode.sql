-- ---------------------------------------------------------------------------
-- 3. What the To Ship dialog needs. Re-reads the order from Pancake first (same as
--    staff_refresh_online_order_lines), so the caller can skip its own refresh afterwards.
--    { sets: [...], packages: [names] } - sets is empty when the order has no SET line.
create or replace function public.staff_get_online_order_set_assembly(
  p_admin_username text,
  p_admin_password text,
  p_order_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
set statement_timeout = '30000'
as $$
declare
  v_line record;
  v_item_code text;
  v_package text;
  v_qty numeric;
  v_display text;
  v_sets jsonb := '[]'::jsonb;
  v_packages jsonb;
begin
  if not public.is_staff_authorized(p_admin_username, p_admin_password) then
    raise exception 'Not authorized.';
  end if;
  if p_order_id is null or trim(p_order_id) = '' then
    raise exception 'Order ID is required.';
  end if;

  perform extensions.http_set_curlopt('CURLOPT_TIMEOUT_MS', '15000');
  begin
    perform public._sync_online_order_detail(p_order_id);
  exception when others then
    raise exception 'Could not re-read order % from Pancake (%). Please try again in a moment.', p_order_id, sqlerrm;
  end;

  for v_line in
    select * from public."OnlineOrderLines"
    where "OrderID" = p_order_id and "LineID" not like '%~SETMAT~%'
    order by "LineID"
  loop
    v_item_code := coalesce(nullif(trim(v_line."ItemCode"), ''), nullif(trim(v_line."product_display_id"), ''));
    if upper(public._online_order_line_category(v_line."VariationId", v_item_code)) <> 'SET' then
      continue;
    end if;

    v_package := public._resolve_set_package(v_line."VariationId", v_item_code);
    v_qty := coalesce(v_line."Quantity", 0);
    v_display := coalesce(nullif(trim(v_line."Description"), ''), v_item_code, v_line."VariationId", 'SET Line ' || v_line."LineID");

    v_sets := v_sets || jsonb_build_array(jsonb_build_object(
      'line_id', v_line."LineID",
      'item_code', v_item_code,
      'variation_id', v_line."VariationId",
      'description', v_display,
      'quantity', v_qty,
      'note', v_line."Note",
      'package_name', v_package,
      -- Already assembled (its "SET Material for ..." lines are on the order) - To Ship skips it; the
      -- Assemble button can still redo it.
      'exploded', exists (
        select 1 from public."OnlineOrderLines" m
        where m."OrderID" = p_order_id and trim(coalesce(m."Note", '')) = 'SET Material for ' || v_display),
      'components', case
        when v_package is not null and v_qty > 0 and v_qty = trunc(v_qty)
          then public._set_components_add_stock(public._set_package_components(v_package, v_qty::int),
                                                public._online_order_warehouse_name(p_order_id))
        else null
      end
    ));
  end loop;

  select coalesce(jsonb_agg(h."PackageName" order by h."PackageName"), '[]'::jsonb) into v_packages
  from public."CompleteAquariumSetHeader" h
  where public._set_package_has_lines(h."PackageName");

  return jsonb_build_object('sets', v_sets, 'packages', v_packages);
end;
$$;

grant execute on function public.staff_get_online_order_set_assembly(text, text, text) to anon;

