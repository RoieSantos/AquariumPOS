-- Category of an order line: Variants by VariationId, then Items by VariationId, then Items by code
-- (same order as OnlineOrdersForm.cs ResolveOnlineLineCategoryCode).
create or replace function public._online_order_line_category(p_variation_id text, p_item_code text)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select trim(v."CategoryCode") from public."Variants" v
      where nullif(trim(p_variation_id), '') is not null
        and v."VariationId" = trim(p_variation_id)
        and nullif(trim(v."CategoryCode"), '') is not null
      limit 1),
    (select trim(i."CategoryCode") from public."Items" i
      where nullif(trim(p_variation_id), '') is not null
        and i."VariationId" = trim(p_variation_id)
        and nullif(trim(i."CategoryCode"), '') is not null
      limit 1),
    (select trim(i."CategoryCode") from public."Items" i
      where nullif(trim(p_item_code), '') is not null
        and (i."Code" = trim(p_item_code) or i."VariationId" = trim(p_item_code))
        and nullif(trim(i."CategoryCode"), '') is not null
      limit 1),
    ''
  );
$$;

create or replace function public._set_package_has_lines(p_package text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public."CompleteAquariumSetLine" l
    where lower(trim(l."PackageName")) = lower(trim(p_package))
